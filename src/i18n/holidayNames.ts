export function getLocalizedHolidayName(
    name: string,
    countryCode: CountryCode,
    language: Language
): string {
    const nativeLang = COUNTRY_NATIVE_LANGUAGE[countryCode];
    if (nativeLang && language === nativeLang) {
        const dict = NATIVE_HOLIDAY_NAMES[nativeLang];
        if (dict && dict[name]) {
            return dict[name];
        }
    }
    return name;
}
